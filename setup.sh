#!/usr/bin/env bash
# Generic setup helper for agy-wrapper-service
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RESET='\033[0m'

printf "${BLUE}Antigravity CLI API Wrapper setup${RESET}\n\n"

if ! command -v docker >/dev/null 2>&1; then
  printf "${YELLOW}Docker was not found. Install Docker and Compose before starting the container.${RESET}\n"
fi

read -r -p "API port [3000]: " USER_PORT
API_PORT="${USER_PORT:-3000}"
if ! [[ "$API_PORT" =~ ^[0-9]+$ ]] || (( API_PORT < 1 || API_PORT > 65535 )); then
  echo "Port must be a number between 1 and 65535." >&2
  exit 1
fi

read -r -p "Default model [gemini-3.8-flash]: " USER_MODEL
CHOSEN_MODEL="${USER_MODEL:-gemini-3.8-flash}"
read -r -p "Default reasoning effort (low/medium/high) [medium]: " USER_LEVEL
CHOSEN_LEVEL="${USER_LEVEL:-medium}"
case "$CHOSEN_LEVEL" in
  low|medium|high) ;;
  *) echo "Reasoning effort must be low, medium, or high." >&2; exit 1 ;;
esac

cat > "$SCRIPT_DIR/.env" <<EOF
# Generated by setup.sh
PORT=${API_PORT}
DEFAULT_MODEL=${CHOSEN_MODEL}
DEFAULT_LEVEL=${CHOSEN_LEVEL}
UPLOAD_DIR=/app/uploads
AGY_PATH=/root/.local/bin/agy
EOF

mkdir -p "$SCRIPT_DIR/docker" "$SCRIPT_DIR/uploads"
touch "$SCRIPT_DIR/uploads/.gitkeep"
ln -sfn ../.env "$SCRIPT_DIR/docker/.env"

if [ -f "$SCRIPT_DIR/bin/ask" ]; then
  if [ "$EUID" -eq 0 ]; then
    INSTALL_DIR="/usr/local/bin"
  else
    INSTALL_DIR="${HOME}/.local/bin"
    mkdir -p "$INSTALL_DIR"
  fi
  install -m 0755 "$SCRIPT_DIR/bin/ask" "$INSTALL_DIR/ask"
  mkdir -p "$HOME/.gemini/antigravity-cli"
  printf 'http://localhost:%s\n' "$API_PORT" > "$HOME/.gemini/antigravity-cli/api_url"
  echo -e "${GREEN}Installed ask at ${INSTALL_DIR}/ask${RESET}"
fi

if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
  read -r -p "Build and start the Docker service now? [Y/n]: " START_DOCKER
  if [[ ! "$START_DOCKER" =~ ^[nN]$ ]]; then
    docker compose -f "$SCRIPT_DIR/docker/docker-compose.yml" up -d --build
  fi
fi

printf "\n${GREEN}Setup complete.${RESET}\n"
printf "API endpoint: http://localhost:%s\n" "$API_PORT"
printf "Use: ask \"your question\"\n"
